function pushPlace({ catId, name, city, cityAdcode, district, districtAdcode, dLng, dLat, rating, cost, why, jitter = 0.06 }) {
  if (!catIds.has(catId)) {
    console.warn(`[warn] 分类 ${catId} 未在 categories.json 定义，跳过 ${name}`);
    return;
  }
  const seedA = hash(catId + name);
  const seedB = hash(name + district + 'y');
  const lng = +(dLng + (seedA - 0.5) * jitter).toFixed(6);
  const lat = +(dLat + (seedB - 0.5) * jitter).toFixed(6);
  const links = buildAmapLinks(name, city, lng, lat);
  places.push({
    id: `seed:${cityAdcode}:${catId}:${hash(name + catId).toString(36).slice(2, 10)}`,
    source: 'seed',
    name,
    categoryId: catId,
    cityAdcode,
    regionAdcode: districtAdcode,
    city,
    district,
    districtAdcode,
    address: `${city}${district}`,
    lng,
    lat,
    rating,
    cost,
    why,
    amapPoiId: null,
    amapUrl: links.place,
    uriSearchUrl: links.uriSearch,
    markerUrl: links.marker,
    naviUrl: links.navi,
    coordPrecision: 'approx',
    fetchedAt: new Date().toISOString(),
  });
  byCat[catId] = (byCat[catId] || 0) + 1;
  byCity[city] = (byCity[city] || 0) + 1;
}

