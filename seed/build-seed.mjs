function buildAmapLinks(name, city, lng, lat) {
  const q = encodeURIComponent(name);
  const c = encodeURIComponent(city);
  return {
    place: null, // 无 poiid 时为空, 由 AmapCollector 补齐
    uriSearch: `https://uri.amap.com/search?keyword=${q}&city=${c}&view=map&callnative=0`,
    marker: `https://uri.amap.com/marker?position=${lng.toFixed(6)},${lat.toFixed(6)}&name=${q}&coordinate=gaode&callnative=1`,
    navi: `https://uri.amap.com/navigation?to=${lng.toFixed(6)},${lat.toFixed(6)},${q}&mode=car&policy=1&src=trip-roulette`,
  };
}

